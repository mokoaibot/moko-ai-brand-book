def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    expected = {f"moko-ai-{deity.slug}.svg" for deity in DEITIES}
    for stale in OUTPUT.glob("*.svg"):
        if stale.name not in expected:
            stale.unlink()
    for deity in DEITIES:
        (OUTPUT / f"moko-ai-{deity.slug}.svg").write_text(svg(deity), encoding="utf-8")
    summary = ", ".join(f"{deity.name} ({len(deity.facets)})" for deity in DEITIES)
    print(f"Built {len(DEITIES)} MOKO AI Pantheon portraits: {summary}")


if __name__ == "__main__":
    main()
