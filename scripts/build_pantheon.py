def facet_markup(deity: Deity) -> str:
    lines = [
        f'  <g id="pantheon-lowpoly-mark" clip-path="url(#{deity.slug}-clip)" '
        f'data-facets="{len(deity.facets)}">'
    ]
    for index, points in enumerate(deity.facets):
        color = PALETTE[(index + deity.palette_offset) % len(PALETTE)]
        lines.append(f'    <polygon points="{points}" fill="{color}"/>')
    lines.append("  </g>")
    return "\n".join(lines)


